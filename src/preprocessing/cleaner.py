def clean_text(text: str, remove_stopwords: bool = False) -> str:
    """
    Cleans raw text:
    - Strips HTML tags
    - Strips URLs
    - Normalizes unicode characters
    - Removes non-alphanumeric punctuation
    - Collapses whitespace
    - Lowercases text
    """
    if not text or not isinstance(text, str):
        return ""

    # Normalize unicode (NFKD)
    text = unicodedata.normalize("NFKD", text)

    # Remove HTML tags
    text = re.sub(r"<[^>]+>", " ", text)

    # Remove URLs
    text = re.sub(r"https?://\S+|www\.\S+", " ", text)

    # Lowercase
    text = text.lower()

    # Remove non-word characters (keep basic alphanumeric and space)
    text = re.sub(r"[^\w\s]", " ", text)

    # Remove digits that are standalone numbers (optional, keeping numbers like 2026 or 2G)
    tokens = text.split()

    if remove_stopwords:
        tokens = [t for t in tokens if t not in COMMON_STOPWORDS and len(t) > 1]

    return " ".join(tokens)


def tokenize_text(text: str) -> List[str]:
    """Tokenizes text for BM25 and bag-of-words operations."""
    cleaned = clean_text(text, remove_stopwords=True)
    if not cleaned:
        return []
    return cleaned.split()
